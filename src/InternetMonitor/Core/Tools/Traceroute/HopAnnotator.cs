using System.Net;
using System.Net.NetworkInformation;
using System.Net.Sockets;
using InternetMonitor.Localization;

namespace InternetMonitor.Core.Tools.Traceroute;

/// <summary>
/// Explains, in plain language, what each hop of a traceroute actually means - and in particular
/// what the asterisks mean.
///
/// A row of stars in a traceroute is the single most misread thing in network diagnostics. People
/// see it and conclude the connection is broken there, when the overwhelmingly common cause is a
/// router that simply does not answer traceroute probes while forwarding traffic perfectly. The
/// distinction is visible in the data - a silent hop followed by an answering one cannot be where
/// the path ends - but only if the probe statuses were kept, which is why v1 could not do this.
///
/// A pure function over the finished hop list, so every rule is testable against a synthetic
/// route.
/// </summary>
public static class HopAnnotator
{
    /// <summary>
    /// Above this difference between consecutive hops, and with a country change, the traffic has
    /// almost certainly crossed a long-haul link. Chosen well above ordinary metro variation.
    /// </summary>
    private const double LongHaulJumpMs = 25;

    public static void Annotate(IReadOnlyList<TracerouteHop> hops, bool reachedDestination)
    {
        LocalizationManager loc = LocalizationManager.Instance;

        for (int i = 0; i < hops.Count; i++)
        {
            hops[i].Annotation = Describe(hops, i, reachedDestination, loc);
        }
    }

    private static string? Describe(IReadOnlyList<TracerouteHop> hops, int index, bool reachedDestination, LocalizationManager loc)
    {
        TracerouteHop hop = hops[index];

        // An explicit unreachable status is the router telling us something definite, and takes
        // precedence over any inference drawn from silence.
        if (hop.ProblemStatus is { } problem)
        {
            string? text = problem switch
            {
                IPStatus.DestinationNetworkUnreachable => loc.Get("hop.netUnreachable"),
                IPStatus.DestinationHostUnreachable => loc.Get("hop.hostUnreachable"),
                IPStatus.DestinationProtocolUnreachable => loc.Get("hop.protocolUnreachable"),
                IPStatus.DestinationPortUnreachable => loc.Get("hop.portUnreachable"),
                IPStatus.TtlReassemblyTimeExceeded => loc.Get("hop.reassemblyTimeout"),
                IPStatus.PacketTooBig => loc.Get("hop.packetTooBig"),
                _ => null,
            };

            if (text is not null)
            {
                return text;
            }
        }

        if (hop.Silent)
        {
            bool answersLater = hops.Skip(index + 1).Any(h => !h.Silent);

            if (answersLater)
            {
                // The decisive case. Something beyond this hop answered, so packets are getting
                // through it; it is simply not replying on its own behalf.
                return loc.Format("hop.silentButRouteWorks", hops.Skip(index + 1).First(h => !h.Silent).Ttl);
            }

            // Only worth saying once, on the first hop of a silent tail.
            bool firstOfTail = index == 0 || !hops[index - 1].Silent;
            if (!firstOfTail)
            {
                return null;
            }

            return reachedDestination
                ? loc.Get("hop.silentNearDestination")
                : loc.Get("hop.silentTail");
        }

        if (hop.LossFraction > 0)
        {
            // Rate limiting versus real loss. A router that answers some probes and drops others
            // while everything downstream is clean is protecting its own control plane, not
            // losing traffic. ICMP replies are generated by the router's CPU and are the first
            // thing it throttles under load.
            bool downstreamClean = hops
                .Skip(index + 1)
                .Where(h => !h.Silent)
                .All(h => h.LossFraction <= 0);

            return downstreamClean
                ? loc.Format("hop.rateLimited", hop.AnsweredCount, hop.Probes.Count)
                : loc.Format("hop.packetLoss", (int)Math.Round(hop.LossFraction * 100));
        }

        if (hop.Responders.Count > 1)
        {
            return loc.Format("hop.loadBalanced", hop.Responders.Count);
        }

        IPAddress address = hop.Responders[0];
        if (IsPrivate(address))
        {
            return loc.Get("hop.privateNetwork");
        }

        if (IsCarrierGradeNat(address))
        {
            return loc.Get("hop.cgnat");
        }

        // A large latency jump on its own is unremarkable - it could be a congested link. Paired
        // with the traffic entering a different country it is almost always a long-haul hop, and
        // saying so turns an alarming number into an expected one.
        if (index > 0 && hop.MinMs is { } here && hops[index - 1].MinMs is { } previous
            && here - previous > LongHaulJumpMs
            && hop.Owner?.CountryCode is { Length: > 0 } country
            && hops[index - 1].Owner?.CountryCode is { Length: > 0 } previousCountry
            && !country.Equals(previousCountry, StringComparison.OrdinalIgnoreCase))
        {
            return loc.Format("hop.longHaul", previousCountry, country, (int)Math.Round(here - previous));
        }

        return null;
    }

    /// <summary>RFC 1918 and link-local - still inside the user's own network.</summary>
    public static bool IsPrivate(IPAddress address)
    {
        if (address.AddressFamily != AddressFamily.InterNetwork)
        {
            return address.IsIPv6LinkLocal || address.IsIPv6SiteLocal;
        }

        byte[] b = address.GetAddressBytes();
        return b[0] == 10
            || (b[0] == 172 && b[1] >= 16 && b[1] <= 31)
            || (b[0] == 192 && b[1] == 168)
            || (b[0] == 169 && b[1] == 254)
            || b[0] == 127;
    }

    /// <summary>
    /// 100.64.0.0/10 - the range providers use between their own equipment and the customer.
    /// Seeing it means the hop is inside the ISP's network rather than on the public internet,
    /// which is worth saying because it looks like a private address but is not one.
    /// </summary>
    public static bool IsCarrierGradeNat(IPAddress address)
    {
        if (address.AddressFamily != AddressFamily.InterNetwork)
        {
            return false;
        }

        byte[] b = address.GetAddressBytes();
        return b[0] == 100 && b[1] >= 64 && b[1] <= 127;
    }

    /// <summary>True for addresses no public registry can say anything useful about.</summary>
    public static bool IsUnroutable(IPAddress address) =>
        IsPrivate(address) || IsCarrierGradeNat(address) || IPAddress.IsLoopback(address);
}
